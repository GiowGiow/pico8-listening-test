"""Build the catalog of the "which song fits this game" study.

Every pair is one game of the frozen test split, shown by its cartridge image:
the game's own song against a song generated by the tag-conditioned model for
the same tag (the tag is the first of the game's BBS tags that the model knows,
the same rule src/conditioning.py used to label the training songs).

* Games: test-split songs of at least --clip-seconds, one song per cartridge,
  in random order (fixed seed), CC-licensed cartridges first. A game is skipped
  when its clip is mostly silent or its cartridge has no label image.
* Generated: samples of the same tag, in random order. The i-th usable sample
  is paired with the i-th game, so nobody chooses which generated song goes
  with which game.
* Both clips go through tools/prepare_songs.py's path: same synth, no SFX
  filters, same length, -16 LUFS, constant-bitrate MP3, random opaque ids.
* The anchor pair, heard last by everyone, is one more game against a sample of
  the group's Markov baseline.

Cartridge images are fetched from the Lexaloffle BBS (the URL recorded in the
dataset), kept in --image-cache, and re-encoded to WebP under an opaque id.

Usage (with the TPfinal-music-rn virtualenv):

    ../TPfinal-music-rn/.venv/bin/python tools/prepare_pairs.py \
        --tp-repo ../TPfinal-music-rn --cond-run <job results>/grid_block-tag --job 23771
"""

import argparse
import json
import os
import random
import secrets
import subprocess
import sys
import tempfile
import time
import urllib.request
from datetime import datetime, timezone
from multiprocessing import Pool
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from prepare_songs import REAL, _init, _render, ffmpeg_mp3, load_tp, song_seconds  # noqa: E402

MARKOV = "pico8_data/samples/markov-grupo/samples.jsonl.gz"
DATASET = "dataset_pico8_v2/dataset_pico8_v2"
USER_AGENT = "pico8-percept-study/1.0 (DCC831 UFMG listening test)"


def game_tags(metadata, tid):
    path = metadata / str(tid) / "game_info.json"
    if not path.exists():
        return [], None
    info = json.loads(path.read_text())
    tags = [str(t).strip().lower().replace(" ", "_") for t in (info.get("tags") or []) if str(t).strip()]
    return tags, info.get("license")


def fetch_cartridge(url, cache):
    """Download a .p8.png once; later runs read it from the cache."""
    path = cache / url.rsplit("/", 1)[-1]
    if not path.exists():
        request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                data = response.read(2_000_000)
        except OSError as exc:
            print(f"  image failed: {url}: {exc}", flush=True)
            return None
        path.write_bytes(data)
        time.sleep(0.5)  # be polite to the BBS
    return path


def cartridge_image(path):
    """The cartridge as an RGB image, or None when it has no label picture."""
    try:
        image = Image.open(path).convert("RGB")
    except OSError:
        return None
    if image.size != (160, 205):
        return None
    label = np.asarray(image.crop((16, 24, 144, 152)))
    # An empty label is a flat dark rectangle; a drawn one has several colors.
    if len(np.unique(label.reshape(-1, 3) // 16, axis=0)) < 4 or label.std() < 12:
        return None
    return image.resize((480, 615), Image.NEAREST)


class Renderer:
    """Render candidates in batches and keep the ones that pass the silence check."""

    def __init__(self, tp, clip_seconds, min_active, tmp, workers):
        self.clip_seconds, self.min_active, self.tmp, self.workers = clip_seconds, min_active, tmp, workers
        self.pool = Pool(workers, initializer=_init, initargs=(str(tp),))
        self.n = 0

    def usable(self, songs):
        """Yield (song, wav, stats) for the usable songs, in the given order."""
        for start in range(0, len(songs), self.workers * 2):
            batch = songs[start:start + self.workers * 2]
            jobs = []
            for song in batch:
                self.n += 1
                jobs.append((song, self.clip_seconds, str(self.tmp / f"cand_{self.n}.wav")))
            for song, job, res in zip(batch, jobs, self.pool.map(_render, jobs)):
                if res and res["active"] >= self.min_active and res["seconds"] >= self.clip_seconds - 0.05:
                    yield song, job[2], res


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tp-repo", type=Path, required=True)
    ap.add_argument("--cond-run", type=Path, required=True,
                    help="results folder of the tag-conditioned run (conditioning.json and samples/TAG_x)")
    ap.add_argument("--system", default="lstm-grid_block-tag")
    ap.add_argument("--job", default="", help="cluster job id of the conditioned run, for the record")
    ap.add_argument("--tags", default="platformer,puzzle,arcade,shmup")
    ap.add_argument("--per-tag", type=int, default=8)
    ap.add_argument("--out", type=Path, default=Path("catalog"))
    ap.add_argument("--image-cache", type=Path, default=Path(".cache/cartridges"))
    ap.add_argument("--clip-seconds", type=float, default=20.0)
    ap.add_argument("--min-active", type=float, default=0.8)
    ap.add_argument("--bitrate", default="128k")
    ap.add_argument("--seed", type=int, default=831)
    ap.add_argument("--workers", type=int, default=os.cpu_count() or 4)
    args = ap.parse_args()

    tp = args.tp_repo.resolve()
    _, read_jsonl, _, sample_rate, samples_per_tick = load_tp(tp)
    rng = random.Random(args.seed)
    tags = args.tags.split(",")
    labels = json.loads((args.cond_run / "conditioning.json").read_text())["labels"]
    known = [label[5:-1] for label in labels if label not in ("<TAG_other>", "<TAG_none>")]
    missing = [t for t in tags if t not in known]
    if missing:
        raise SystemExit(f"the model has no token for {missing}; it knows {known}")

    metadata = tp / DATASET / "metadata"
    cart_url = {}
    with open(tp / DATASET / "dataset.jsonl") as f:
        for line in f:
            row = json.loads(line)
            cart_url[str(row["tid"])] = row["cart_url_remote"]

    audio_dir, image_dir = args.out / "audio", args.out / "images"
    for d in (audio_dir, image_dir, args.image_cache):
        d.mkdir(parents=True, exist_ok=True)

    def long_enough(songs):
        return [s for s in songs if song_seconds(s, sample_rate, samples_per_tick) >= args.clip_seconds]

    # Real songs by tag: shuffled, CC-licensed cartridges first, one song per cartridge.
    by_tag, seen = {t: [] for t in tags}, set()
    real = long_enough(read_jsonl(tp / REAL))
    rng.shuffle(real)
    for song in real:
        tid = str(song["tid"])
        game, license_ = game_tags(metadata, tid)
        tag = next((t for t in game if t in known), None)
        if tag in by_tag and tid not in seen and tid in cart_url:
            seen.add(tid)
            by_tag[tag].append((song, license_))
    for tag in tags:
        by_tag[tag].sort(key=lambda x: not str(x[1] or "").startswith("CC"))  # stable

    songs, pairs = [], []

    def add_song(song, wav, res, system, kind, source_id, tag):
        sid = secrets.token_hex(8)
        lufs = ffmpeg_mp3(wav, str(audio_dir / f"{sid}.mp3"), args.clip_seconds, args.bitrate)
        songs.append({
            "id": sid, "system": system, "kind": kind, "tag": tag, "source_id": source_id,
            "seconds": round(res["seconds"], 2), "active": round(res["active"], 3), "input_lufs": round(lufs, 1),
        })
        return sid

    def games(renderer, candidates, n):
        """The first n games with a usable clip and a cartridge that has a label."""
        chosen = []
        for (song, wav, res) in renderer.usable([s for s, _ in candidates]):
            if len(chosen) == n:
                break
            tid = str(song["tid"])
            path = fetch_cartridge(cart_url[tid], args.image_cache)
            image = cartridge_image(path) if path else None
            if image is None:
                print(f"  skipped game {tid}: no label image", flush=True)
                continue
            chosen.append((song, wav, res, image))
        return chosen

    for f in list(audio_dir.glob("*.mp3")) + list(image_dir.glob("*.webp")):
        f.unlink()

    with tempfile.TemporaryDirectory() as tmpdir:
        renderer = Renderer(tp, args.clip_seconds, args.min_active, Path(tmpdir), args.workers)
        licenses = {str(s["tid"]): lic for t in tags for s, lic in by_tag[t]}

        def add_pair(tag, role, game, generated, system, sample_file):
            song, wav, res, image = game
            gen, gen_wav, gen_res = generated
            tid = str(song["tid"])
            image_id = secrets.token_hex(8)
            image.save(image_dir / f"{image_id}.webp", "WEBP", quality=90, method=6)
            human = add_song(song, wav, res, "real", "human", f"test:{tid}:{song['song_id']}", tag)
            genai = add_song(gen, gen_wav, gen_res, system, "genai", f"{sample_file}:{gen['song_id']}", tag)
            pairs.append({
                "id": secrets.token_hex(8), "tag": tag, "role": role, "human": human, "genai": genai,
                "image": image_id,
                "game": {"tid": tid, "url": f"https://www.lexaloffle.com/bbs/?tid={tid}",
                         "cartridge": cart_url[tid], "license": licenses.get(tid)},
            })

        spare = None
        for tag in tags:
            print(f"{tag}: {len(by_tag[tag])} candidate games", flush=True)
            extra = 1 if spare is None else 0  # one more game of the first tag, for the anchor
            chosen = games(renderer, by_tag[tag], args.per_tag + extra)
            if len(chosen) < args.per_tag + extra:
                raise SystemExit(f"{tag}: only {len(chosen)} usable games, wanted {args.per_tag + extra}")
            if extra:
                spare = (tag, chosen.pop())
            sample_file = f"samples/TAG_{tag}"
            folder = args.cond_run / "samples" / f"TAG_{tag}"
            samples = folder / "samples.jsonl.gz"
            everything = read_jsonl(samples if samples.exists() else folder / "samples.jsonl")
            pool = long_enough(everything)
            print(f"{tag}: {len(pool)} of {len(everything)} generated songs >= {args.clip_seconds:g} s", flush=True)
            rng.shuffle(pool)
            generated = []
            for item in renderer.usable(pool):
                generated.append(item)
                if len(generated) == args.per_tag:
                    break
            if len(generated) < args.per_tag:
                raise SystemExit(f"{tag}: only {len(generated)} usable generated clips of {len(pool)} long enough")
            for game, gen in zip(chosen, generated):
                add_pair(tag, "pool", game, gen, args.system, sample_file)
            print(f"{tag}: {len(chosen)} pairs", flush=True)

        markov = long_enough(read_jsonl(tp / MARKOV))
        rng.shuffle(markov)
        anchor_tag, anchor_game = spare
        add_pair(anchor_tag, "anchor", anchor_game, next(renderer.usable(markov)), "markov", "markov-grupo")
        renderer.pool.terminate()

    git = subprocess.run(["git", "-C", str(tp), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    catalog = {
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "clip_seconds": args.clip_seconds,
        "seed": args.seed,
        "synth": {"tp_commit": git, "sfx_filters": False},
        "tags": tags,
        "generated": {"system": args.system, "job": args.job, "sampling": "top-p 0.95, one control token per tag"},
        "songs": songs,
        "pairs": pairs,
    }
    (args.out / "catalog.json").write_text(json.dumps(catalog, indent=1) + "\n")
    print(f"catalog: {len(pairs)} pairs, {len(songs)} clips -> {args.out / 'catalog.json'}")


if __name__ == "__main__":
    main()
